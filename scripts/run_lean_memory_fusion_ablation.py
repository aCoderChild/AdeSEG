FORMAT = "adeseg_lean_memory_fusion_video_v3"


def file_sha256(path):
    h = hashlib.sha256()
    with Path(path).open("rb") as stream:
        for chunk in iter(lambda: stream.read(1048576), b""):
            h.update(chunk)
    return h.hexdigest()


def require_digest(value):
    if not (isinstance(value, str) and len(value) == 64
            and all(c in "0123456789abcdef" for c in value)):
        raise ValueError("Expected lowercase SHA256 digest")
    return value


def load_frozen_prompts(path, videos):
    """One immutable prompt per eligible video; missing videos are explicit skips."""
    path = Path(path).resolve(strict=True)
    prompts = {}
    for lineno, line in enumerate(path.read_text("utf8").splitlines(), 1):
        if not line.strip():
            continue
        try:
            row = json.loads(line)
        except json.JSONDecodeError as exc:
            raise ValueError(f"Bad prompt JSON line {lineno}") from exc
        expected = {"video_id", "frame_index", "mask_path", "image_sha256",
                    "mask_sha256", "prompt_origin"}
        if not isinstance(row, dict) or set(row) != expected:
            raise ValueError(f"Unexpected prompt fields on line {lineno}")
        video, frame_idx = row["video_id"], row["frame_index"]
        if (video not in videos or video in prompts or type(frame_idx) is not int
                or frame_idx not in {f.frame_index for f in videos[video]}):
            raise ValueError(f"Unknown, duplicate or invalid prompt at line {lineno}")
        if row["prompt_origin"] != "automatic_mask":
            raise ValueError("Only externally frozen automatic-mask prompts are supported")
        image = next(f for f in videos[video] if f.frame_index == frame_idx)
        mask_path = (path.parent / str(row["mask_path"])).resolve()
        if (not mask_path.is_file()
            or (image.mask_path is not None and
                mask_path == image.mask_path.resolve())):
            raise ValueError("Missing prompt mask or GT-path prompt leakage")
        if (file_sha256(image.image_path) != require_digest(row["image_sha256"])
                or file_sha256(mask_path) != require_digest(row["mask_sha256"])):
            raise ValueError("Frozen prompt checksum mismatch")
        prompts[video] = dict(row, resolved_mask=str(mask_path))
    if not prompts:
        raise ValueError("No frozen automatic prompts supplied")
    return prompts


def get_fusion(arm, checkpoint, checkpoint_sha256, backbone_sha256,
               train_manifest_sha256, device, input_mode="full"):
    if input_mode not in EarlyFeatureMemoryFusion.INPUT_MODES:
        raise ValueError("Invalid fusion input mode")
    if arm != "fusion" and input_mode != "full":
        raise ValueError("Input ablations require a separately trained fusion checkpoint")
    if arm == "native":
        if any(x is not None for x in (checkpoint, checkpoint_sha256, train_manifest_sha256)):
            raise ValueError("Native arm must not receive a fusion checkpoint")
        return None, None
    if arm == "identity":
        if any(x is not None for x in (checkpoint, checkpoint_sha256, train_manifest_sha256)):
            raise ValueError("Identity arm must use a fresh zero-initialized module")
        return EarlyFeatureMemoryFusion().to(device).eval(), None
    if arm != "fusion" or checkpoint is None or checkpoint_sha256 is None or train_manifest_sha256 is None:
        raise ValueError("Trained fusion requires checkpoint and provenance SHA256")
    checkpoint = Path(checkpoint).resolve(strict=True)
    if file_sha256(checkpoint) != require_digest(checkpoint_sha256):
        raise ValueError("Trained fusion checkpoint file SHA256 mismatch")
    require_digest(train_manifest_sha256)
    payload = torch.load(checkpoint, map_location="cpu", weights_only=True)
    if not isinstance(payload, dict) or not isinstance(payload.get("config"), dict):
        raise ValueError("Malformed memory-fusion checkpoint")
    from training.lean_memory_fusion import TRAINING_PROTOCOL, training_source_sha256
    from training.split_guard import sha256 as training_sha256
    source_capture_sha = training_sha256(
        Path(__file__).resolve().parents[1] / "scripts/capture_lean_memory_train.py")
    if (payload.get("training_protocol") != TRAINING_PROTOCOL
            or payload.get("fusion_input_mode") != input_mode
            or payload.get("training_source_sha256") != training_source_sha256()
            or payload.get("capture_source_sha256") != source_capture_sha
            or not isinstance(payload.get("split_file_sha256"), str)
            or len(payload["split_file_sha256"]) != 64
            or type(payload.get("capture_count")) is not int
            or payload["capture_count"] < 1):
        raise ValueError("Unverified memory-fusion training protocol or split receipt")
    config = MemoryFeatureFusionConfig(**payload["config"])
    fusion = EarlyFeatureMemoryFusion(config)
    fusion.load_trained_state(
        payload,
        backbone_sha256=backbone_sha256,
        train_manifest_sha256=train_manifest_sha256,
    )
    if fusion.is_identity_initialized():
        raise ValueError("Trained-fusion arm has no learned memory residual")
    return fusion.to(device).eval(), file_sha256(checkpoint)


def summarize_resident_memory(state):
    """Observable retained spatial memory, not total attention or VRAM cost.

    Native Lean includes separate pointer/insurance/TCIM storage; these counters
    characterize the currently resident frame entries only.
    """
    objects = state.get("output_dict_per_obj", {})
    if not isinstance(objects, dict) or len(objects) != 1:
        raise ValueError("Expected one Lean per-object output dictionary")
    rows = []
    for obj in objects.values():
        for kind in ("cond_frame_outputs", "non_cond_frame_outputs"):
            bank = obj.get(kind)
            if not isinstance(bank, dict):
                raise ValueError("Missing Lean output memory bank")
            for frame_idx, entry in sorted(bank.items()):
                if not isinstance(entry, dict):
                    raise ValueError("Malformed stored memory entry")
                dense, compact = entry.get("maskmem_features"), entry.get("maskmem_features_seq")
                if compact is not None:
                    if not isinstance(compact, torch.Tensor) or compact.ndim != 3:
                        raise ValueError("Malformed compressed Lean memory")
                    count = int(compact.shape[0])
                    reported = entry.get("smr_pruned_token_count")
                    if reported is not None and count != reported:
                        raise ValueError("Compressed memory metadata disagrees with real tokens")
                    storage = "compressed"
                elif dense is not None:
                    if not isinstance(dense, torch.Tensor) or dense.ndim != 4:
                        raise ValueError("Malformed dense Lean memory")
                    count = int(dense.shape[-2] * dense.shape[-1])
                    storage = "dense"
                else:
                    continue
                rows.append({
                    "frame_idx": int(frame_idx), "kind": kind,
                    "tokens": count, "storage": storage,
                    "protected": bool(entry.get("smr_protected", False)),
                })
    insurance = state.get("insurance_mem_bank", {})
    if not isinstance(insurance, dict):
        raise ValueError("Unexpected insurance memory representation")
    return {
        "resident_frame_entries": len(rows),
        "resident_spatial_tokens": sum(x["tokens"] for x in rows),
        "compressed_frame_entries": sum(x["storage"] == "compressed" for x in rows),
        "protected_frame_entries": sum(x["protected"] for x in rows),
        "insurance_entries": sum(len(x) for x in insurance.values()),
        "note": "Resident snapshot only; does not include transient attention tensors or object pointers",
    }


def infer_sequence(predictor, frames, prompt, folder, fusion, arm, device,
                   input_mode="full"):
    """Run causal one-shot propagation, recording masks but never reading GT."""
    from scripts.memory_token_io import synchronize_storage
    frame_to_position = {f.frame_index: i for i, f in enumerate(frames)}
    start = frame_to_position[prompt["frame_index"]]
    # The pinned author Lean runner assumes the single prompt occupies its
    # local frame zero. Keep original source indices in the receipt only.
    staged_frames = frames[start:]
    rows, telemetry, frame_memory_snapshots = [], [], []
    with tempfile.TemporaryDirectory(prefix="adeseg_lean_mem_") as temporary:
        stage_frames(staged_frames, Path(temporary))
        state = None
        with torch.inference_mode():
            try:
                state = predictor.init_state(
                    video_path=temporary, offload_video_to_cpu=True,
                    offload_state_to_cpu=False,
                )
                with Image.open(prompt["resolved_mask"]) as image:
                    pixels = np.asarray(image.convert("L"))
                hw = (int(state["video_height"]), int(state["video_width"]))
                if pixels.shape != hw or not np.isin(pixels, (0, 255)).all():
                    raise ValueError("Frozen prompt mask must be binary 0/255 at original resolution")
                mask = torch.from_numpy((pixels > 0).copy())
                if not bool(mask.any().item()):
                    raise ValueError("Frozen automatic prompt is empty")
                predictor.add_new_mask(state, frame_idx=0, obj_id=1, mask=mask)
                context = (nullcontext() if fusion is None else
                           route_memory_feature_fusion(
                               predictor, fusion,
                               identity_control=(arm == "identity"),
                               telemetry=telemetry, input_mode=input_mode))
                synchronize_storage(device)
                beginning = time.perf_counter()
                with context:
                    for index, obj_ids, logits in predictor.propagate_in_video(
                        state, start_frame_idx=0, reverse=False
                    ):
                        if list(obj_ids) != [1] or tuple(logits.shape) != (1, 1, *hw):
                            raise RuntimeError("Unexpected Lean object ID or mask geometry")
                        if not bool(torch.isfinite(logits).all().item()):
                            raise FloatingPointError("Non-finite Lean inference logits")
                        # Inspect resident memory after each emitted frame. The
                        # snapshot is a storage audit, NOT the complete attention
                        # tensor byte count or true peak allocated GPU memory.
                        frame_memory_snapshots.append({
                            "local_frame_index": int(index),
                            "source_frame_index": int(staged_frames[index].frame_index),
                            "memory": summarize_resident_memory(state),
                        })
                        if index == 0:
                            continue
                        if index != len(rows) + 1:
                            raise RuntimeError("Missing, duplicated, or out-of-order video frames")
                        source_frame = staged_frames[index]
                        logit_bytes = (logits.detach().float().cpu().contiguous()
                                       .numpy().tobytes())
                        prediction = (logits[0, 0].detach().float().cpu().numpy() > 0)
                        output_path = folder / f"{source_frame.frame_index:06d}.png"
                        if output_path.exists():
                            raise FileExistsError(output_path)
                        Image.fromarray(prediction.astype(np.uint8) * 255).save(output_path)
                        rows.append({
                            "frame_index": source_frame.frame_index,
                            "image_sha256": file_sha256(source_frame.image_path),
                             "prediction_file": output_path.name,
                            "prediction_sha256": file_sha256(output_path),
                            "logits_sha256": hashlib.sha256(logit_bytes).hexdigest(),
                        })
                synchronize_storage(device)
                duration = time.perf_counter() - beginning
                resident = summarize_resident_memory(state)
            finally:
                if state is not None:
                    predictor.reset_state(state)
    if len(rows) != len(staged_frames) - 1:
        raise RuntimeError("Incomplete Lean propagation")
    effective_future_writes = sum(
        t["changed_elements_after_bf16"] > 0 and
        t["frame_idx"] < len(staged_frames) - 1
        for t in telemetry)
    if fusion is not None:
        # A learned fusion that never executes is NOT an evaluated intervention.
        if rows and len(telemetry) == 0:
            raise RuntimeError("Memory fusion hook was never exercised")
        if any(t["native_token_count"] != t["enriched_token_count"] for t in telemetry):
            raise RuntimeError("Memory token budget changed")
        if arm == "identity" and any(t["changed_elements"] for t in telemetry):
            raise RuntimeError("Zero-residual identity violated")
        if arm == "identity" and effective_future_writes:
            raise RuntimeError("Identity control changed the BF16 memory bank")
        # A per-sequence zero is a valid observation (e.g. predicted absence).
        # Abort only when an entire fusion run has no causally effective writes.
    return {
        "status": "completed",
        "prompt_frame_index": prompt["frame_index"],
        "prompt_mask_sha256": prompt["mask_sha256"],
        "prompt_image_sha256": prompt["image_sha256"],
        "prompt_origin": prompt["prompt_origin"],
        "predictions": rows,
        "memory_writes_checked": len(telemetry),
        "memory_writes_modified": sum(t["changed_elements"] > 0 for t in telemetry),
        "effective_memory_writes_affecting_future": effective_future_writes,
        "resident_memory": resident,
        "per_frame_resident_memory": frame_memory_snapshots,
        "memory_writes_quantized_changed": sum(
            t.get("changed_elements_after_bf16", 0) > 0 for t in telemetry
        ),
        "anchor_similarity_audit": {
            "eligible_writes": sum(
                t.get("anchor_reference_available", False) for t in telemetry),
            "mean_abs_similarity_shift": (
                sum(t["anchor_similarity_mean_abs_shift"]
                    for t in telemetry if t.get("anchor_reference_available"))
                / sum(t.get("anchor_reference_available", False) for t in telemetry)
                if any(t.get("anchor_reference_available", False) for t in telemetry)
                else None
            ),
            "note": "Fixed-anchor cosine drift at memory WRITE; not TAMP Top-K outcomes.",
        },
        "memory_write_telemetry": telemetry,
        "propagation_seconds": duration,
    }


def run(args):
    from scripts.run_author_baseline import build_author_predictor, source_identity

    manifest = args.manifest.resolve(strict=True)
    prompt_manifest = args.prompt_manifest.resolve(strict=True)
    checkpoint = args.checkpoint.resolve(strict=True)
    output = args.output.resolve()
    if output.exists():
        raise FileExistsError("Refusing to overwrite existing ablation output")
    input_mode = getattr(args, "fusion_input_mode", "full")
    if input_mode not in EarlyFeatureMemoryFusion.INPUT_MODES:
        raise ValueError("Invalid fusion input mode")
    if args.arm != "fusion" and input_mode != "full":
        raise ValueError("Only the trained fusion arm accepts input ablation modes")
    if args.split not in ("dev", "test") or args.label_id != 1:
        raise ValueError("This PolypGen protocol requires split dev/test and label ID 1")
    if file_sha256(checkpoint) != require_digest(args.checkpoint_sha256):
        raise ValueError("Lean backbone checkpoint SHA256 mismatch")
    repo, revision = source_identity("lean")
    videos = load_manifest(
        manifest, args.split, require_contiguous=True,
        require_jpeg=True, safe_output_ids=True, require_masks=False,
    )
    frozen = load_frozen_prompts(prompt_manifest, videos)
    # Validate all parameters and the source-bound adapter BEFORE creating output.
    if args.arm in ("identity", "fusion"):
        get_fusion(args.arm, args.fusion_checkpoint, args.fusion_sha256,
                   args.checkpoint_sha256, args.train_manifest_sha256,
                   "cpu", input_mode=input_mode)
    output.mkdir(parents=True)
    sequences = {}
    for video_id, frames in sorted(videos.items()):
        if video_id not in frozen:
            sequences[video_id] = {"status": "no_initialization", "predictions": []}
            continue
        model = build_author_predictor(
            SimpleNamespace(method="lean", checkpoint=checkpoint, device=args.device),
            repo,
        )
        fusion, fusion_digest = get_fusion(
            args.arm, args.fusion_checkpoint, args.fusion_sha256,
            args.checkpoint_sha256, args.train_manifest_sha256,
            args.device, input_mode=input_mode,
        )
        folder = output / "predictions" / video_id
        folder.mkdir(parents=True, exist_ok=False)
        sequences[video_id] = infer_sequence(
            model, frames, frozen[video_id], folder, fusion, args.arm,
            args.device, input_mode=input_mode
        )
        print(f"[{args.arm}] {video_id}: {len(sequences[video_id]['predictions'])} propagated frames", flush=True)
        del model, fusion
    if args.arm == "fusion":
        eligible = [
            r for r in sequences.values()
            if r.get("status") == "completed" and len(r["predictions"]) >= 2
        ]
        if eligible and not any(
                r.get("effective_memory_writes_affecting_future", 0) > 0
                for r in eligible):
            raise RuntimeError(
                "Trained fusion produced no BF16-visible memory changes that "
                "could influence a later scored frame in the entire cohort")
    root = Path(__file__).resolve().parents[1]
    source_head = subprocess.check_output(
        ["git", "-C", str(root), "rev-parse", "HEAD"], text=True).strip()
    if subprocess.check_output(
        ["git", "-C", str(root), "status", "--porcelain", "--untracked-files=no"],
        text=True).strip():
        raise RuntimeError("Tracked AdeSEG code changed during a frozen experiment")
    runtime_signature = {
        "adeseg_head": source_head,
        "runner_sha256": file_sha256(Path(__file__).resolve()),
        "fusion_source_sha256": implementation_sha256(),
        "torch_version": str(torch.__version__),
        "python_version": platform.python_version(),
        "device": args.device,
        "precision": "native build force_fp32; no autocast",
        "lean_config_sha256": file_sha256(repo / "configs/lean_sam2/lean_sam2.yaml"),
        "lvos_config_sha256": file_sha256(repo / "configs/runtime/lvos.yaml"),
        "sam_config_sha256": file_sha256(repo / "sam2/configs/sam2.1/sam2.1_hiera_b+.yaml"),
        "bypass_sha256": file_sha256(repo / "checkpoints/bypass_bottleneck_base.pth"),
    }
    receipt = {
        "format": FORMAT,
        "runtime_signature": runtime_signature,
        "track": "lean_sam2_hiera_bplus",
        "arm": args.arm,
        "fusion_input_mode": input_mode,
        "split": args.split,
        "label_id": args.label_id,
        "manifest_sha256": file_sha256(manifest),
        "prompt_manifest_sha256": file_sha256(prompt_manifest),
        "backbone_sha256": file_sha256(checkpoint),
        "lean_source_revision": revision,
        "fusion_checkpoint_sha256": fusion_digest if args.arm == "fusion" else None,
        "fusion_implementation_sha256": implementation_sha256() if args.arm != "native" else None,
        "sequences": sequences,
        "warning": "Predictions only. Input manifest must be image-only; no GT paths are accepted or read.",
    }
    (output / "receipt.json").write_text(json.dumps(receipt, indent=2) + "\n", encoding="utf8")
    return receipt


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--arm", choices=("native", "identity", "fusion"), required=True)
    p.add_argument("--fusion-input-mode",
                   choices=EarlyFeatureMemoryFusion.INPUT_MODES, default="full",
                   help="Must match the mode used to train the fusion checkpoint")
    p.add_argument("--manifest", type=Path, required=True)
    p.add_argument("--prompt-manifest", type=Path, required=True)
    p.add_argument("--checkpoint", type=Path, required=True)
    p.add_argument("--checkpoint-sha256", required=True)
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--split", choices=("dev", "test"), default="dev")
    p.add_argument("--label-id", type=int, default=1)
    p.add_argument("--device", choices=("cpu", "mps", "cuda"), default="cuda")
    p.add_argument("--fusion-checkpoint", type=Path)
    p.add_argument("--fusion-sha256")
    p.add_argument("--train-manifest-sha256")
    args = p.parse_args(argv)
    result = run(args)
    print(json.dumps({
        "arm": result["arm"], "output": str(args.output),
        "completed_sequences": sum(v["status"] == "completed" for v in result["sequences"].values()),
    }, indent=2))


if __name__ == "__main__":
    main()
