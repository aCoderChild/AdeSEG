"""Matched Lean-SAM2 memory-fusion ablation inference; NO GT scoring in this stage.

Runs B0 native, B1 zero-residual identity, or B2 trained memory enrichment.
Each run uses the SAME externally frozen initialization-mask manifest.
The first prompt is an image/mask pair produced by a prior automatic pipeline,
never a ground-truth mask generated by this script. It does not redetect.

The script records exact prediction masks/hashes. Use
scripts.score_lean_memory_ablations to compute Dice *after* predictions freeze.
"""
